/**
 * Typed key lookup with optional {placeholder} interpolation.
 * t(lang, 'events.sectionTitle', { city: 'Chennai' })
 */
export function t(
  lang: Language,
  path: string,
  values?: Record<string, string | number>,
): string {
  const keys = path.split('.');
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  let node: any = translations[lang];
  for (const k of keys) {
    node = node?.[k];
  }
  if (typeof node !== 'string') return path;
  if (!values) return node;
  return node.replace(/\{(\w+)\}/g, (_, k) => String(values[k] ?? `{${k}}`));
}
